// Generates src/katex-css.ts from the installed katex package:
//   node scripts/gen-katex-css.mjs
// The result is committed, so building the package never needs katex installed. Re-run it (and the
// katex-css test) when katex is upgraded.
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(path.join(here, "../package.json"));
const katexDir = path.dirname(require.resolve("katex/package.json"));
const { version } = JSON.parse(fs.readFileSync(path.join(katexDir, "package.json"), "utf8"));
const css = fs.readFileSync(path.join(katexDir, "dist", "katex.min.css"), "utf8");

// Every @font-face becomes [family, style, weight, file]; only the woff2 file is kept (the engine reads
// woff2, and one source per face keeps the page small). The rest of the stylesheet is emitted as is.
const faces = [...css.matchAll(/@font-face\{([^}]*)\}/g)].map((m) => {
  const body = m[1];
  const get = (prop) => new RegExp(`${prop}:([^;]+)`).exec(body)[1];
  return [get("font-family"), get("font-style"), get("font-weight"), /url\(fonts\/([^)]+\.woff2)\)/.exec(body)[1]];
});
const rules = css.replace(/@font-face\{[^}]*\}/g, "").trim();

const out = `// Generated by scripts/gen-katex-css.mjs from katex@${version}. Do not edit.

/** The katex version the stylesheet and font list below were taken from. */
export const KATEX_CSS_VERSION = ${JSON.stringify(version)};

/** [family, style, weight, woff2 file] of every KaTeX font. */
export const KATEX_FONT_FACES: readonly (readonly [string, string, string, string])[] = ${JSON.stringify(faces)};

/** katex.min.css without its @font-face rules. */
export const KATEX_RULES = ${JSON.stringify(rules)};
`;
fs.writeFileSync(path.join(here, "../src/katex-css.ts"), out);
console.log(`katex ${version}: ${faces.length} font faces, ${rules.length} bytes of rules`);
